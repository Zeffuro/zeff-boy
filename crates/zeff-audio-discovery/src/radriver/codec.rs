pub(super) fn inspect(
    bytes: &[u8],
    mixer: RomSpan,
    state: u32,
    budget: &mut Budget<'_>,
) -> ReadResult<[RomSpan; 2]> {
    let at = mixer.effective_offset as usize;
    let differences = word(bytes, at + 0x2a0).ok_or(ReadError::Invalid)?;
    let transitions = word(bytes, at + 0x2a4).ok_or(ReadError::Invalid)?;
    let differences = pointer(bytes, differences, 49 * 16 * 2)?;
    let transitions = pointer(bytes, transitions, 49 * 8)?;
    for (index, &opcode) in MIXER.iter().enumerate() {
        budget.charge()?;
        let expected = match index * 4 {
            0xec | 0x2a8 | 0x344 => state,
            0x2a0 => differences.canonical_cpu_address,
            0x2a4 => transitions.canonical_cpu_address,
            _ => opcode,
        };
        if word(bytes, at + index * 4) != Some(expected) {
            return Err(ReadError::Invalid);
        }
    }
    let start = transitions.effective_offset as usize;
    for &next in &bytes[start..start + transitions.byte_len as usize] {
        budget.charge()?;
        if next >= 49 {
            return Err(ReadError::Invalid);
        }
    }
    Ok([differences, transitions])
}
