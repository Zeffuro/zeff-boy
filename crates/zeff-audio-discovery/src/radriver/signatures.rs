pub(super) fn matches(bytes: &[u8], at: usize, pattern: &[u16]) -> bool {
    let mut index = 0;
    while index < pattern.len() {
        let expected = pattern[index];
        let Some(actual) = half(bytes, at + index * 2) else {
            return false;
        };
        if expected & 0xf800 == 0xf000
            && pattern.get(index + 1).is_some_and(|v| v & 0xf800 == 0xf800)
        {
            if actual & 0xf800 != 0xf000
                || half(bytes, at + index * 2 + 2).is_none_or(|v| v & 0xf800 != 0xf800)
            {
                return false;
            }
            index += 2;
        } else {
            let mask = if expected & 0xf800 == 0x4800 {
                0xff00
            } else {
                0xffff
            };
            if actual & mask != expected & mask {
                return false;
            }
            index += 1;
        }
    }
    true
}
