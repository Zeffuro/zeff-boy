pub(in crate::nes_native) fn rom(relocated: bool) -> Vec<u8> {
    let header = if relocated { 0x9462_u16 } else { 0x8462 };
    let offset = usize::from(header - 0x8000) + 16;
    let mut bytes = super::rom(relocated);
    bytes[offset..offset + DATA.len()].copy_from_slice(DATA);
    for &at in WORDS {
        let target = u16::from_le_bytes([DATA[at], DATA[at + 1]]);
        bytes[offset + at..offset + at + 2].copy_from_slice(&(header + target).to_le_bytes());
    }
    bytes
}

