pub fn ram_fixture_rom() -> Vec<u8> {
    let mut bytes = fixture_rom();
    bytes[0x147..0x14a].copy_from_slice(&[0x1b, 6, 2]);
    checksum(&mut bytes);
    bytes
}

fn checksum(bytes: &mut [u8]) {
    bytes[0x14d] = bytes[0x134..0x14d]
        .iter()
        .fold(0_u8, |sum, byte| sum.wrapping_sub(*byte).wrapping_sub(1));
}
