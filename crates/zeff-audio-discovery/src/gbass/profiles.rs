use super::{GbassBankSelector, GbassNativeProfile, GbassSchedule, GbassStartupGuard, RomSpan};

#[derive(Clone, Copy)]
pub(super) struct Profile {
    pub id: &'static str,
    pub sha256: &'static str,
    pub rom_len: usize,
    pub header: &'static [u8; 16],
    pub schedule: GbassSchedule,
    pub hardware_started_before_handoff: bool,
    pub guards: &'static [GbassStartupGuard],
    pub config: usize,
    pub layout: super::separate::ConfigurationLayout,
    pub song_count: u16,
    pub instruments: u16,
    pub samples: u16,
    pub sample_steps: &'static [u32],
    pub sample_flags: &'static [u32],
    pub bank: Option<GbassBankSelector>,
    pub module: Option<super::GbassModule>,
    pub partial_warning: Option<&'static str>,
    pub handoff: (usize, usize),
    pub init: (usize, usize),
    pub start: (usize, usize),
    pub play: (usize, usize),
    pub vblank: (usize, usize),
    pub update: (usize, usize),
    pub wrapper: (usize, usize),
    pub wait: (usize, usize),
    pub irq: (usize, usize),
    pub irq_address: u32,
    pub irq_table: (usize, usize),
    pub irq_table_address: u32,
    pub state_address: u32,
    pub sample_data: (usize, usize),
    pub instrument_data: (usize, usize),
    pub channel_data: (usize, usize),
    pub title_data: (usize, usize),
    pub sequences: (usize, usize),
}

impl Profile {
    pub fn native(
        &self,
        song_table: RomSpan,
        sample_table: RomSpan,
        instrument_table: RomSpan,
        instrument_types: RomSpan,
        sequence_bank: RomSpan,
    ) -> GbassNativeProfile {
        let span = |(offset, len)| RomSpan::new(offset, len);
        GbassNativeProfile {
            bank: self.bank,
            module: self.module,
            profile: self.id,
            schedule: self.schedule,
            hardware_started_before_handoff: self.hardware_started_before_handoff,
            startup_guards: self.guards.to_vec(),
            handoff: span(self.handoff),
            init: span(self.init),
            hardware_start: span(self.start),
            play: span(self.play),
            vblank: span(self.vblank),
            update: span(self.update),
            update_wrapper: span(self.wrapper),
            vblank_wait: span(self.wait),
            irq_handler: span(self.irq),
            irq_handler_address: self.irq_address,
            irq_table: span(self.irq_table),
            irq_table_address: self.irq_table_address,
            state_address: self.state_address,
            song_table,
            sample_table,
            instrument_table,
            instrument_types,
            sequence_bank,
        }
    }
}

pub(super) fn all_profiles() -> impl Iterator<Item = &'static Profile> {
    let profiles = PROFILES
        .iter()
        .chain(super::banked::PROFILES.iter())
        .chain(super::separate::PROFILES.iter())
        .chain(super::modules::PROFILES.iter());
    #[cfg(any(test, feature = "test-support"))]
    let profiles = profiles.chain([
        &super::fixture::PROFILE,
        &super::fixture::IRQ_PROFILE,
        &super::fixture::STARTED_PROFILE,
        &super::fixture::PARTIAL_PROFILE,
        &super::fixture::BANKED_PROFILES[0],
        &super::fixture::BANKED_PROFILES[1],
        &super::module_fixture::PROFILES[0],
        &super::module_fixture::PROFILES[1],
        &super::separate_fixture::PROFILE,
    ]);
    profiles
}

