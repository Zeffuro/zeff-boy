pub(super) struct Pattern {
    pub code: &'static [u8],
    pub ignored: &'static [usize],
    pub irq: bool,
    pub call_offset: usize,
}

impl Pattern {
    pub fn matches(&self, bytes: &[u8], at: usize) -> bool {
        bytes
            .get(at..at.saturating_add(self.code.len()))
            .is_some_and(|candidate| {
                candidate
                    .iter()
                    .zip(self.code)
                    .enumerate()
                    .all(|(index, (actual, expected))| {
                        self.ignored.contains(&index) || actual == expected
                    })
            })
    }
}

