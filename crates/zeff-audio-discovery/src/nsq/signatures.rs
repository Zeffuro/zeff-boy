pub(super) fn matches(bytes: &[u8], at: usize, pattern: &[u16]) -> bool {
    pattern.iter().enumerate().all(|(index, expected)| {
        let mask = if expected & 0xf000 == 0xf000 {
            0xf800
        } else {
            0xffff
        };
        half(bytes, at + index * 2).is_some_and(|actual| actual & mask == expected & mask)
    })
}
