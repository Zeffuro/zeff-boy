pub(super) fn rom(region: u8, mapper: u8) -> Vec<u8> {
    let banks = if mapper == 34 { 2 } else { 1 };
    let mut rom = vec![0; 16 + banks * 0x8000 + 0x2000];
    rom[..4].copy_from_slice(b"NES\x1a");
    rom[4] = (banks * 2) as u8;
    rom[5] = 1;
    rom[6] = (mapper << 4) | 2;
    rom[7] = mapper & 0xf0;
    match region {
        1 => rom[9] = 1,
        2 => {
            rom[7] |= 8;
            rom[10] = 0x70;
            rom[12] = 3;
        }
        _ => {}
    }
    let reset = [
        0x78, 0xd8, 0xa2, 0xff, 0x9a, 0xa9, 0x00, 0x8d, 0x00, 0x20, 0x8d, 0x01, 0x20, 0xa9, 0x0f,
        0x8d, 0x15, 0x40, 0xa9, 0xbf, 0x8d, 0x00, 0x40, 0x8d, 0x04, 0x40, 0xa9, 0x60, 0x8d, 0x02,
        0x40, 0x8d, 0x06, 0x40, 0xa9, 0x08, 0x8d, 0x03, 0x40, 0x8d, 0x07, 0x40, 0xa9, 0xff, 0x8d,
        0x08, 0x40, 0xa9, 0x40, 0x8d, 0x0a, 0x40, 0x8d, 0x0b, 0x40, 0xa9, 0x3a, 0x8d, 0x0c, 0x40,
        0xa9, 0x05, 0x8d, 0x0e, 0x40, 0xa9, 0x08, 0x8d, 0x0f, 0x40, 0xa9, 0x8f, 0x8d, 0x10, 0x40,
        0xa9, 0x00, 0x8d, 0x12, 0x40, 0xa9, 0x01, 0x8d, 0x13, 0x40, 0xa9, 0x1f, 0x8d, 0x15, 0x40,
        0xa9, 0x40, 0x8d, 0x17, 0x40, 0xa9, 0x0a, 0x8d, 0x01, 0x20, 0xa9, 0x80, 0x8d, 0x00, 0x20,
        0x58,
    ];
    let nmi = [
        0x48, 0x8a, 0x48, 0xa9, 0x01, 0x8d, 0x16, 0x40, 0xa9, 0x00, 0x8d, 0x16, 0x40, 0x85, 0x00,
        0x85, 0x01, 0xa2, 0x08, 0xad, 0x16, 0x40, 0x4a, 0x26, 0x00, 0xad, 0x17, 0x40, 0x4a, 0x26,
        0x01, 0xca, 0xd0, 0xf1, 0xa5, 0x00, 0x8d, 0x00, 0x60, 0x8d, 0x02, 0x40, 0xa5, 0x01, 0x8d,
        0x01, 0x60, 0x8d, 0x06, 0x40, 0xa5, 0x00, 0x29, 0x01, 0x8d, 0xfd, 0x7f, 0xad, 0x00, 0x90,
        0x8d, 0x03, 0x60, 0x68, 0xaa, 0x68, 0x40,
    ];
    let irq = [
        0x48, 0xee, 0x02, 0x60, 0xa9, 0x0f, 0x8d, 0x15, 0x40, 0xa9, 0x1f, 0x8d, 0x15, 0x40, 0x68,
        0x40,
    ];
    for bank in 0..banks {
        let prg = &mut rom[16 + bank * 0x8000..16 + (bank + 1) * 0x8000];
        prg[..reset.len()].copy_from_slice(&reset);
        let idle = 0x8000u16 + reset.len() as u16;
        prg[reset.len()..reset.len() + 5].copy_from_slice(&[
            0x78,
            0x58,
            0x4c,
            idle as u8,
            (idle >> 8) as u8,
        ]);
        prg[0x100..0x100 + nmi.len()].copy_from_slice(&nmi);
        prg[0x200..0x200 + irq.len()].copy_from_slice(&irq);
        prg[0x1000] = 0x31 + bank as u8;
        prg[0x4000..0x4011].fill(0xa5);
        prg[0x7ffa..0x8000].copy_from_slice(&[0, 0x81, 0, 0x80, 0, 0x82]);
    }
    rom
}
