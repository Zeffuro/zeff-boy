pub fn rom() -> Vec<u8> {
    let mut rom = vec![0; 16 + 0x8000 + 0x2000];
    rom[..4].copy_from_slice(b"NES\x1a");
    rom[4] = 2;
    rom[5] = 1;
    rom[6] = 0x22;
    rom[7] = 0x20;
    let reset = [
        0x78, 0xd8, 0xa2, 0xff, 0x9a, // SEI; CLD; initialize stack
        0xa9, 0x00, 0x8d, 0x00, 0x20, 0x8d, 0x01, 0x20, 0x2c, 0x02, 0x20, 0x10,
        0xfb, // wait for vblank
        0xa9, 0x3f, 0x8d, 0x06, 0x20, 0xa9, 0x00, 0x8d, 0x06, 0x20, 0xa9, 0x0f, 0x8d, 0x07, 0x20,
        0xa9, 0x01, 0x8d, 0x07, 0x20, 0xa9, 0x02, 0x8d, 0x07, 0x20, 0xa9, 0x03, 0x8d, 0x15, 0x40,
        0xa9, 0xbf, 0x8d, 0x00, 0x40, 0x8d, 0x04, 0x40, 0xa9, 0x08, 0x8d, 0x03, 0x40, 0x8d, 0x07,
        0x40, 0xa9, 0x00, 0x8d, 0x05, 0x20, 0x8d, 0x05, 0x20, 0xa9, 0x0a, 0x8d, 0x01, 0x20, 0xa9,
        0x80, 0x8d, 0x00, 0x20,
    ];
    let prg = &mut rom[16..16 + 0x8000];
    prg[..reset.len()].copy_from_slice(&reset);
    let idle = 0x8000u16 + reset.len() as u16;
    prg[reset.len()..reset.len() + 3].copy_from_slice(&[0x4c, idle as u8, (idle >> 8) as u8]);
    let nmi = [
        0x48, 0x8a, 0x48, // preserve A/X
        0xa9, 0x01, 0x8d, 0x16, 0x40, 0xa9, 0x00, 0x8d, 0x16, 0x40, 0x85, 0x00, 0x85, 0x01, 0xa2,
        0x08, 0xad, 0x16, 0x40, 0x4a, 0x26, 0x00, 0xad, 0x17, 0x40, 0x4a, 0x26, 0x01, 0xca, 0xd0,
        0xf1, 0xa5, 0x00, 0x4d, 0x00, 0x60, 0x8d, 0x00, 0x60, 0xa5, 0x01, 0x4d, 0x01, 0x60, 0x8d,
        0x01, 0x60, 0xa5, 0x00, 0x09, 0x20, 0x8d, 0x02, 0x40, 0xa5, 0x01, 0x09, 0x40, 0x8d, 0x06,
        0x40, 0x2c, 0x02, 0x20, 0xa9, 0x3f, 0x8d, 0x06, 0x20, 0xa9, 0x01, 0x8d, 0x06, 0x20, 0xa5,
        0x00, 0x29, 0x3f, 0x8d, 0x07, 0x20, 0xa5, 0x01, 0x29, 0x3f, 0x8d, 0x07, 0x20, 0xa9, 0x00,
        0x8d, 0x05, 0x20, 0x8d, 0x05, 0x20, 0x68, 0xaa, 0x68, 0x40,
    ];
    prg[0x100..0x100 + nmi.len()].copy_from_slice(&nmi);
    prg[0x7ffa..0x8000].copy_from_slice(&[0x00, 0x81, 0x00, 0x80, 0x00, 0x81]);
    for row in 0..8 {
        rom[16 + 0x8000 + row] = 0xaa;
        rom[16 + 0x8000 + row + 8] = 0x55;
    }
    rom
}
